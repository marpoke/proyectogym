    private final RutinaEjercicioC detalleC = new RutinaEjercicioC();
    private final int rutinaId;
    private final List<Item> ejercicios;
    private final DefaultTableModel modelo = Ui.modelo("ID", "Ejercicio", "Series", "Repeticiones");

    public DialogRutinaEjercicios(Window padre, int rutinaId, String titulo) {
        super(padre, "Ejercicios de la rutina: " + titulo, ModalityType.APPLICATION_MODAL);
        this.rutinaId = rutinaId;
        initComponents();
        proyectgymit.util.Atajos.escCierra(this, this::dispose);
        tabla.setModel(modelo);
        this.ejercicios = Ui.llenarCombo(comboEjercicio, new EjerciciosC().listarEjerciciosCombo());
        boolean escribe = Permisos.puedeEscribir(Modulo.RUTINAS);
        Ui.habilitar(escribe, comboEjercicio, spnSeries, spnRepeticiones, btnAgregar, btnQuitar);
        cargar();
        setLocationRelativeTo(padre);
    }

    private void cargar() {
        modelo.setRowCount(0);
        for (Object[] fila : detalleC.listarDetalle(rutinaId)) modelo.addRow(fila);
    }

    private void agregar() {
        Permisos.exigirEscritura(Modulo.RUTINAS);
        int ej = Ui.idSeleccionado(comboEjercicio, ejercicios);
        if (ej < 0) { Ui.error(this, "No hay ejercicios en el catálogo. Regístrelos primero en «Ejercicios»."); return; }
        RutinaEjercicio d = new RutinaEjercicio();
        d.setRutinaID(rutinaId);
        d.setEjercicioID(ej);
        d.setSeries((Integer) spnSeries.getValue());
        d.setRepeticiones((Integer) spnRepeticiones.getValue());
        if (detalleC.agregarEjercicioARutina(d)) cargar(); else Ui.error(this, "No se pudo agregar el ejercicio.");
    }

    private void quitar() {
        Permisos.exigirEscritura(Modulo.RUTINAS);
        Integer id = Ui.idDeFila(tabla, 0);
        if (id == null) { Ui.error(this, "Seleccione un ejercicio de la tabla."); return; }
        if (detalleC.quitarEjercicioDeRutina(id)) cargar(); else Ui.error(this, "No se pudo quitar el ejercicio.");
    }

