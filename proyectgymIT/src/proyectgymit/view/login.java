    private static final long BLOQUEO_MS = 30_000;
    private int intentosFallidos = 0;
    private long bloqueadoHasta = 0;

    /** Valida las credenciales (PBKDF2, ~1 s) en segundo plano para no congelar la ventana. */
    private void autenticar() {
        long ahora = System.currentTimeMillis();
        if (ahora < bloqueadoHasta) {
            Ui.error(this, "Demasiados intentos fallidos. Espere " + ((bloqueadoHasta - ahora) / 1000 + 1) + " segundos.");
            return;
        }
        final String correo = jTextField6.getText().trim();
        final char[] password = jTextField7.getPassword();
        if (correo.isEmpty() || password.length == 0) {
            Ui.error(this, "Escriba su correo y su contraseña.");
            return;
        }
        jButton6.setEnabled(false);
        new javax.swing.SwingWorker<Usuario, Void>() {
            @Override
            protected Usuario doInBackground() {
                try {
                    return new UsuarioC().iniciarSesion(correo, password);
                } finally {
                    java.util.Arrays.fill(password, '\0');
                }
            }

            @Override
            protected void done() {
                jButton6.setEnabled(true);
                try {
                    Usuario u = get();
                    if (u == null) {
                        intentosFallidos++;
                        jTextField7.setText("");
                        if (intentosFallidos >= MAX_INTENTOS) {
                            intentosFallidos = 0;
                            bloqueadoHasta = System.currentTimeMillis() + BLOQUEO_MS;
                            Ui.error(login.this, "Demasiados intentos fallidos. Intente de nuevo en 30 segundos.");
                        } else {
                            Ui.error(login.this, "Correo o contraseña incorrectos.");
                        }
                        return;
                    }
                    abrirSegunRol(u);
                } catch (InterruptedException | java.util.concurrent.ExecutionException ex) {
                    logger.log(java.util.logging.Level.SEVERE, null, ex);
                    Ui.error(login.this, "No se pudo iniciar sesion. Revise la conexion a la base de datos.");
                }
            }
        }.execute();
    }

    /** CLIENTE -> portal del socio; el resto -> panel de gestion filtrado por rol. */
    private void abrirSegunRol(Usuario u) {
        if (!Permisos.puedeVer(u.getRol(), Modulo.PORTAL_SOCIO) && !Permisos.puedeVer(u.getRol(), Modulo.DASHBOARD)) {
            Ui.error(this, "Su rol (" + u.getRol() + ") no tiene acceso al sistema.");
            return;
        }
        Sesion.iniciar(u);
        if (Permisos.CLIENTE.equalsIgnoreCase(u.getRol())) new MenuCliente().setVisible(true);
        else new MenuPrincipal().setVisible(true);
        dispose();
    }

