    private void aplicarPermisos() {
        boolean escribe = Permisos.puedeEscribir(Modulo.EJERCICIOS);
        Ui.habilitar(escribe, jButton3, jButton4, jButton6, jTextField6, jTextField7, jComboBox4);
    }

    private void cargarTabla() {
        modelo.setRowCount(0);
        for (Ejercicios e : ejerciciosC.listarEjercicios()) {
            modelo.addRow(new Object[]{e.getId(), e.getNombre(), e.getGrupoMuscular(), e.getDescripcion()});
        }
    }

    private void cargarSeleccion() {
        seleccionado = Ui.idDeFila(jTable1, 0);
        if (seleccionado == null) return;
        int f = jTable1.getSelectedRow();
        jTextField6.setText(String.valueOf(jTable1.getValueAt(f, 1)));
        jComboBox4.setSelectedItem(String.valueOf(jTable1.getValueAt(f, 2)));
        Object d = jTable1.getValueAt(f, 3);
        jTextField7.setText(d == null ? "" : d.toString());
    }

    private void limpiar() {
        jTable1.clearSelection();
        seleccionado = null;
        jTextField6.setText("");
        jTextField7.setText("");
        jComboBox4.setSelectedIndex(0);
    }

    private Ejercicios leerFormulario() {
        if (Ui.vacio(jTextField6.getText())) { Ui.error(this, "El nombre del ejercicio es obligatorio."); return null; }
        Ejercicios e = new Ejercicios();
        e.setNombre(jTextField6.getText().trim());
        e.setGrupoMuscular(String.valueOf(jComboBox4.getSelectedItem()));
        e.setDescripcion(jTextField7.getText().trim());
        return e;
    }

    private void guardar() {
        Permisos.exigirEscritura(Modulo.EJERCICIOS);
        Ejercicios e = leerFormulario();
        if (e == null) return;
        if (ejerciciosC.registrarEjercicios(e)) { Ui.info(this, "Ejercicio guardado."); limpiar(); cargarTabla(); }
        else Ui.error(this, "No se pudo guardar el ejercicio.");
    }

    private void editar() {
        Permisos.exigirEscritura(Modulo.EJERCICIOS);
        if (seleccionado == null) { Ui.error(this, "Seleccione un ejercicio de la tabla."); return; }
        Ejercicios e = leerFormulario();
        if (e == null) return;
        e.setId(seleccionado);
        if (ejerciciosC.actualizarEjercicios(e)) { Ui.info(this, "Ejercicio actualizado."); limpiar(); cargarTabla(); }
        else Ui.error(this, "No se pudo actualizar el ejercicio.");
    }

    private void eliminar() {
        Permisos.exigirEscritura(Modulo.EJERCICIOS);
        if (seleccionado == null) { Ui.error(this, "Seleccione un ejercicio de la tabla."); return; }
        if (!Ui.confirmar(this, "Se eliminará el ejercicio y se quitará de todas las rutinas que lo usan.\n¿Desea continuar?")) return;
        Ejercicios e = new Ejercicios();
        e.setId(seleccionado);
        if (ejerciciosC.eliminarEjercicios(e)) { Ui.info(this, "Ejercicio eliminado."); limpiar(); cargarTabla(); }
        else Ui.error(this, "No se pudo eliminar el ejercicio.");
    }

