    public DialogRecibo(Window padre, int id, String cliente, double monto, String metodo, LocalDate fecha) {
        super(padre, ModalityType.APPLICATION_MODAL);
        this.id = id;
        initComponents();
        panelRecibo1.setDatos(id, cliente, monto, metodo, fecha);
        Atajos.escCierra(this, this::dispose);
        setLocationRelativeTo(padre);
    }

    private void imprimir() {
        PrinterJob job = PrinterJob.getPrinterJob();
        job.setJobName("Recibo " + id);
        job.setPrintable(panelRecibo1);
        if (job.printDialog()) {
            try { job.print(); } catch (PrinterException ex) { Ui.error(this, "No se pudo imprimir: " + ex.getMessage()); }
        }
    }

