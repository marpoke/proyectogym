    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
       String correo = txtCorreo.getText();
       String password = new String(txtPassword.getPassword());
       UsuarioC controlador = new UsuarioC();
       Usuario validacion = controlador.iniciarSesion(correo, password);
       if (validacion != null){
           String rol = validacion.getRol();
           switch (rol){
               case "ADMIN" -> {
                   admin pantallaadmin = new admin();
                   pantallaadmin.setVisible(true);
                   break;
               }
               case "RECEPCION" -> {
                   JRecepcion pantallarecepcion = new JRecepcion();
                   pantallarecepcion.setVisible(true);
                   break;
               }
               case "ENTRENADOR" -> {
                   JEntrenador pantallaentrenador = new JEntrenador();
                   pantallaentrenador.setVisible(true);
                   break;
               }
               case "CLIENTE" -> {
                       JCliente pantallacliente = new JCliente();
                       pantallacliente.setVisible(true);
                       break;
                
           }
           
       }
       }
    }//GEN-LAST:event_jButton1ActionPerformed

